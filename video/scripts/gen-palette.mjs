#!/usr/bin/env node
// Generates src/palette.ts from the app's own sources, so a colour that is not in the app
// cannot exist in the video (board rev E "Look" 1):
//   node scripts/gen-palette.mjs
// Reads src/app/globals.css (Sorbet neutrals, the dark accent, border, radius, dither
// colours), src/lib/run-view.ts (ROLE_COLOR) and src/components/nimbus/timeline.tsx (the
// model badge). The boot sky and the cloud's two colours are the only values written here by
// hand; the script checks each still sits on its source line and stops if one has moved.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const VIDEO = join(dirname(fileURLToPath(import.meta.url)), "..");
const REPO = join(VIDEO, "..");
const read = (p) => readFileSync(join(REPO, p), "utf8");

const css = read("src/app/globals.css");
const lines = css.split("\n");

/** The value and 1-based line of `--name` inside the first block whose selector line matches `sel`. */
function token(name, sel = null) {
  let inside = sel === null;
  let depth = 0;
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i];
    if (!inside && sel.test(l.trim())) {
      inside = true;
      depth = 0;
    }
    if (inside) {
      const m = l.match(new RegExp(`^\\s*--${name}:\\s*([^;]+);`));
      if (m) return { value: m[1].trim(), line: i + 1 };
      if (sel !== null) {
        depth += (l.match(/{/g) || []).length - (l.match(/}/g) || []).length;
        if (depth <= 0 && l.includes("}")) inside = false;
      }
    }
  }
  throw new Error(`globals.css has no --${name}${sel ? ` in ${sel}` : ""}`);
}
const DARK = /^\.dark\s*{/;
const at = (t, label = "") => `// src/app/globals.css:${t.line}  ${label}`.trimEnd();
const neutral = (n) => token(`color-neutral-${n}`);

// The dark dither colours (the second .dark block, inside @layer base)
function darkDither(name) {
  for (let i = lines.length - 1; i >= 0; i--) {
    if (!/^\s*\.dark\s*{/.test(lines[i])) continue;
    for (let j = i; j < lines.length && !lines[j].includes("}"); j++) {
      const m = lines[j].match(new RegExp(`--dither-${name}:\\s*([^;]+);`));
      if (m) return { value: m[1].trim(), line: j + 1 };
    }
  }
  throw new Error(`globals.css has no dark --dither-${name}`);
}

const runView = read("src/lib/run-view.ts").split("\n");
const roleStart = runView.findIndex((l) => l.includes("export const ROLE_COLOR"));
if (roleStart < 0) throw new Error("run-view.ts has no ROLE_COLOR");
const role = {};
for (let i = roleStart + 1; i < runView.length && !runView[i].startsWith("}"); i++) {
  const m = runView[i].match(/^\s*(\w+):\s*"([^"]+)"/);
  if (m) role[m[1]] = { value: m[2], line: i + 1 };
}
// ROLE_COLOR refers to CSS variables for two roles; resolve them against globals.css
const resolve = (v) => {
  const m = v.match(/^var\(--([\w-]+)\)$/);
  if (!m) return v;
  return m[1] === "rb-accent" ? token("rb-accent", DARK).value : token(m[1]).value;
};

const timeline = read("src/components/nimbus/timeline.tsx").split("\n");
const badgeLine = timeline.findIndex((l) => /bg-\[#[0-9a-f]{6}\][^"]*text-black/.test(l));
if (badgeLine < 0) throw new Error("timeline.tsx: the model badge is gone");
const badge = timeline[badgeLine].match(/bg-\[(#[0-9a-f]{6})\]/)[1];

// ── The only hand-added values, each checked against its source line ──────────────────────
const HAND = [
  {
    file: "src/components/nimbus/boot.tsx",
    line: 15,
    must: ["rgba(90, 205, 255, 0.45)", "#1659c8", "#2aa6e6"],
  },
  { file: "src/components/glow-cloud.tsx", line: 302, must: ["#18b2ff"] },
  { file: "src/components/glow-cloud.tsx", line: 326, must: ["#fa7342"] },
];
for (const h of HAND) {
  const l = read(h.file).split("\n")[h.line - 1] ?? "";
  for (const s of h.must) if (!l.includes(s)) throw new Error(`${h.file}:${h.line} no longer has ${s}; update gen-palette.mjs`);
}

const n = Object.fromEntries([50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950].map((k) => [k, neutral(k)]));
const accent = token("rb-accent", DARK);
const accentFg = token("rb-accent-fg", DARK);
const border = token("border", DARK);
const radius = token("rb-radius");
const cell = darkDither("cell");
const dc = Object.fromEntries(["blue", "purple", "green", "orange", "red"].map((k) => [k, darkDither(`color-${k}`)]));

const out = `// GENERATED by scripts/gen-palette.mjs from the app's CSS. Do not edit; re-run the script.
// The app is dark (\`<html class="dark">\`, src/app/layout.tsx); every value below is read
// from the source line named beside it. Node scripts import this file too (no fonts here).

export const N = {
${Object.entries(n)
  .map(([k, t]) => `  ${k}: "${t.value}", ${at(t, `--color-neutral-${k}`)}`)
  .join("\n")}
} as const;

export const C = {
  bg: N[950], // the app shell background
  card: N[900],
  raised: N[800],
  dim: N[600],
  faint: N[500], // the preview watermark
  muted: N[400],
  soft: N[300], // the dither ink
  ink: N[100],
  ${at(border, ".dark --border")}
  line: "${border.value}",
  ${at(accent, ".dark --rb-accent (mint)")}
  mint: "${accent.value}",
  ${at(accentFg, ".dark --rb-accent-fg")}
  mintInk: "${accentFg.value}",
  ${at(dc.red, ".dark --dither-color-red (failures)")}
  red: "${dc.red.value}",
} as const;

${at(radius, "--rb-radius")}
export const RADIUS = ${parseFloat(radius.value)};

// src/lib/run-view.ts:${roleStart + 1} ROLE_COLOR (lane and badge colours in the run view)
export const ROLE = {
${Object.entries(role)
  .map(([k, t]) => `  ${k}: "${resolve(t.value)}", // run-view.ts:${t.line}  ${t.value}`)
  .join("\n")}
} as const;

// src/components/nimbus/overview.tsx TIER_COLOR { ultra: blue, super: purple, nano: green }
// → the .dark --dither-color-* values the charts paint with.
export const TIER = {
  ultra: "${dc.blue.value}", ${at(dc.blue, "--dither-color-blue")}
  super: "${dc.purple.value}", ${at(dc.purple, "--dither-color-purple")}
  nano: "${dc.green.value}", ${at(dc.green, "--dither-color-green")}
} as const;

// src/components/nimbus/timeline.tsx:${badgeLine + 1}, the model badge on every lane (footage only;
// listed so scripts/qa-frames.py counts it as the app's own).
export const NVIDIA_BADGE = "${badge}";

// ── Hand-added (checked against the source line by the generator) ─────────────────────────
// src/components/glow-cloud.tsx:302 and :326, the cloud's own blue and orange. Only where
// the cloud itself is drawn.
export const CLOUD = { blue: "#18b2ff", orange: "#fa7342" } as const;

// src/components/nimbus/boot.tsx:15, the boot screen's sky (the Lockup and the end card).
export const BOOT_SKY =
  "radial-gradient(60% 55% at 62% 42%, rgba(90, 205, 255, 0.45), transparent 70%), linear-gradient(180deg, #1659c8, #2aa6e6)";
/** The same sky as a plain gradient, for type filled with it (background-clip: text). */
export const BOOT_SKY_FILL = "linear-gradient(180deg, #1659c8, #2aa6e6)";

// ── The app's dither texture ──────────────────────────────────────────────────────────────
${at(cell, ".dark --dither-cell")}
export const DITHER_CELL = ${parseFloat(cell.value)};
/** The ground of every motion scene: neutral-950 with a ${parseFloat(cell.value)} px cell of neutral-300 at 3 %. No
 *  colour wash, no glow (board rev E "Look" 2). */
export const DITHER = \`radial-gradient(circle at 1px 1px, color-mix(in oklch, \${N[300]} 3%, transparent) 1px, transparent 1.2px) 0 0 / ${parseFloat(cell.value)}px ${parseFloat(cell.value)}px\`;
/** \`background\` for a motion scene: the dither over neutral-950. */
export const GROUND = \`\${DITHER}, \${N[950]}\`;
`;
writeFileSync(join(VIDEO, "src/palette.ts"), out);
console.log(`palette.ts: ${Object.keys(n).length} neutrals, accent ${accent.value}, ${Object.keys(role).length} roles, 3 tiers, badge ${badge}`);
