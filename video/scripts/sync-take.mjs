// Writes src/take.ts from a take's beats.json: the video path, every beat's window and its
// callout target boxes (take pixels). Cuts, camera focus points, callout rings and sound cues
// all read it, so they agree. The video is always 16:9 and the boxes are written in 1920-wide
// take pixels: a take recorded at device scale 2 (3840 × 2160) has its beats.json boxes in
// device pixels when they reach past 1920, and those are halved here (the 4K master then
// gets the take's own pixels; a 1080p take is upscaled 2× by the 4K render). Re-run after a
// new take:
//   node scripts/sync-take.mjs demo/raw/nimbus-demo-20261027-1633.webm
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
// node scripts/sync-take.mjs <video under public/> [beats file under public/] [module name]
// The module defaults to src/take.ts (the live take); a second take for some scenes gets its own
// module, e.g. `… demo/raw/beats-20261028-1258.json take-1258`.
const [video, beatsArg, moduleName = "take"] = process.argv.slice(2);
if (!video) {
  console.error("usage: node scripts/sync-take.mjs <video path under public/> [beats.json] [module]");
  process.exit(1);
}
const beatsPath = path.join(root, "public", beatsArg ?? path.join(path.dirname(video), "beats.json"));
const beats = JSON.parse(readFileSync(beatsPath, "utf8"));
const list = Array.isArray(beats) ? beats : beats.beats;
const width = Number(
  execFileSync("ffprobe", ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width", "-of", "csv=p=0", path.join(root, "public", video)])
    .toString()
    .trim(),
);
// boxes past 1920 are device pixels of a scale-2 take
const reach = Math.max(0, ...list.flatMap((b) => Object.values(b.targets ?? {}).map((t) => t.x + t.w)));
const k = width > 1920 && reach > 1920 ? width / 1920 : 1;
const norm = (t) => ({ x: t.x / k, y: t.y / k, w: t.w / k, h: t.h / k });
const out = `// Generated by scripts/sync-take.mjs from ${path.relative(root, beatsPath)}. Do not edit.
export const TAKE_FILE = ${JSON.stringify(video)};
/** The take's own width in pixels (${width}); target boxes below are in 1920-wide take pixels. */
export const TAKE_SOURCE_W = ${width};

export type Box = { x: number; y: number; w: number; h: number };
export type TakeBeat = { beat: string; tStart: number; tEnd: number; targets: Record<string, Box> };

export const BEATS: TakeBeat[] = ${JSON.stringify(
  list.map((b) => ({
    beat: b.beat,
    tStart: b.tStart,
    tEnd: b.tEnd,
    targets: Object.fromEntries(Object.entries(b.targets ?? {}).map(([n, t]) => [n, norm(t)])),
  })),
  null,
  2,
)};
`;
writeFileSync(path.join(root, `src/${moduleName}.ts`), out);
console.log(`src/${moduleName}.ts: ${list.length} beats from ${video} (${width} px wide${k !== 1 ? `, boxes ÷${k}` : width < 3840 ? ", the 4K master upscales it 2×" : ""})`);
